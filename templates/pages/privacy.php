  <h1 class="h2">Privacy Policy</h1>
  <p class="text-muted">Draft text: IHA should review and approve this policy (ideally with legal advice) before the portal goes live.</p>

  <h2 class="h5 mt-4">What we collect</h2>
  <p>To process your application we collect your name, email address, date of birth, identification number (CNIC/B-Form), contact and address details, school or college and examination information, parent or guardian details, and optional travel history you choose to provide.</p>

  <h2 class="h5 mt-4">How we use it</h2>
  <p>We use this information to create and verify your account, process and review your application, check it against the published eligibility criteria, issue verification credentials, and contact you about your application. We do not sell your information.</p>

  <h2 class="h5 mt-4">Who can see it</h2>
  <p>Only you can see your own application. Authorised IHA administrators can see applications according to their role. A public verification page, reached by scanning a QR code, shows only a limited result such as the Student ID and whether the code is currently valid; it never shows your date of birth, address, marks, family details or identification number.</p>

  <h2 class="h5 mt-4">Protection</h2>
  <p>Passwords are stored only as secure hashes. Access to records is restricted by role, and sensitive administrative actions are logged.</p>

  <h2 class="h5 mt-4">Retention and your rights</h2>
  <p>Records are kept for as long as IHA policy and applicable law require. To ask about correcting or deleting your information, use the contact details on the home page.</p>
